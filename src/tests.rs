/// Lowercase hex, for comparing byte strings against published vectors.
#[must_use]
pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::with_capacity(bytes.len() * 2), |mut out, b| {
        let _ = write!(out, "{b:02x}");
        out
    })
}

/// A deterministic test pattern of `width` x `height` RGB8 pixels: every pixel differs from its
/// neighbours, so a misplaced row or column shows up in a comparison.
#[must_use]
pub fn pattern_rgb(width: u16, height: u16) -> Vec<u8> {
    let mut out = Vec::with_capacity(usize::from(width) * usize::from(height) * 3);
    for y in 0..height {
        for x in 0..width {
            // Truncation is the point: the channels wrap to make a varied pattern.
            #[allow(clippy::cast_possible_truncation)]
            out.extend_from_slice(&[(x * 7 + y) as u8, (y * 5 + x * 3) as u8, (x ^ y) as u8]);
        }
    }
    out
}
